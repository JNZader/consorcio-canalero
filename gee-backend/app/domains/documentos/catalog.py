_BY_ID: dict[str, DocumentoCatalogo] = {d.id: d for d in DOCUMENTOS}


def list_documentos(group: str | None = None) -> tuple[DocumentoCatalogo, ...]:
    """Return catalog rows, optionally filtered by exact group key."""
    if group is None:
        return DOCUMENTOS
    return tuple(d for d in DOCUMENTOS if d.group == group)


def get_documento(dossier_id: str) -> DocumentoCatalogo | None:
    return _BY_ID.get(dossier_id)


def get_archivo(dossier_id: str, file_id: str) -> tuple[DocumentoCatalogo, ArchivoCatalogo] | None:
    doc = _BY_ID.get(dossier_id)
    if doc is None:
        return None
    for archivo in doc.files:
        if archivo.id == file_id:
            return doc, archivo
    return None
