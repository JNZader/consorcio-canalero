"""Wave 1 PostGIS GiST indexes and redundant GeoAlchemy2 index cleanup.

Creates missing GiST indexes on ``vt_parcelas_catastro``, ``zonas_operativas``
(#742), and ``puntos_conflicto``, and drops redundant autogenerated ``idx_*``
GiST indexes when an explicit ``ix_*`` GiST index covers the exact same column.

Revision ID: zz_wave1_postgis_indexes
Revises: zz_informes_area_campo
"""

from typing import Sequence, Union

from alembic import op

revision: str = "zz_wave1_postgis_indexes"
down_revision: Union[str, None] = "zz_informes_area_campo"
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None

APP_ROLE = "consorcio_app"

VT_PARCELAS_GIST_SQL = f"""
DO $vt_gist$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public'
          AND c.relname = 'vt_parcelas_catastro'
          AND c.relkind = 'm'
    ) THEN
        EXECUTE
            'CREATE INDEX IF NOT EXISTS ix_vt_parcelas_catastro_geometria '
            'ON public.vt_parcelas_catastro USING gist (geometria)';
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{APP_ROLE}') THEN
            EXECUTE
                'ALTER INDEX public.ix_vt_parcelas_catastro_geometria OWNER TO {APP_ROLE}';
        END IF;
    END IF;
END
$vt_gist$;
"""

MISSING_GIST_INDEXES_SQL = """
DO $missing_gist$
DECLARE
    rec record;
BEGIN
    FOR rec IN
        SELECT *
        FROM (
            VALUES
                ('zonas_operativas', 'geometria', 'ix_zonas_operativas_geometria'),
                ('puntos_conflicto', 'geometria', 'ix_puntos_conflicto_geometria')
        ) AS t(table_name, col_name, idx_name)
    LOOP
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = rec.table_name
              AND column_name = rec.col_name
        ) AND NOT EXISTS (
            SELECT 1
            FROM pg_index i
            JOIN pg_class c ON c.oid = i.indrelid
            JOIN pg_namespace n ON n.oid = c.relnamespace
            JOIN pg_class ic ON ic.oid = i.indexrelid
            JOIN pg_am am ON am.oid = ic.relam
            JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = i.indkey[0]
            WHERE n.nspname = 'public'
              AND c.relname = rec.table_name
              AND i.indisvalid
              AND am.amname = 'gist'
              AND a.attname = rec.col_name
        ) THEN
            EXECUTE format(
                'CREATE INDEX IF NOT EXISTS %I ON public.%I USING gist (%I)',
                rec.idx_name,
                rec.table_name,
                rec.col_name
            );
        END IF;
    END LOOP;
END
$missing_gist$;
"""

DEDUP_GIST_INDEXES_SQL = r"""
DO $dedup_gist$
DECLARE
    rec record;
BEGIN
    FOR rec IN
        SELECT
            n.nspname AS schema_name,
            dup_ic.relname AS dup_index
        FROM pg_class c
        JOIN pg_namespace n ON n.oid = c.relnamespace
        JOIN pg_index dup_i ON dup_i.indrelid = c.oid AND dup_i.indisvalid
        JOIN pg_class dup_ic ON dup_ic.oid = dup_i.indexrelid
        JOIN pg_am dup_am ON dup_am.oid = dup_ic.relam AND dup_am.amname = 'gist'
        JOIN pg_attribute dup_a
          ON dup_a.attrelid = c.oid AND dup_a.attnum = dup_i.indkey[0]
        WHERE n.nspname = 'public'
          AND c.relname IN (
              'parcelas_catastro',
              'suelos_catastro',
              'canales_geo',
              'caminos_geo',
              'canal_suggestions',
              'denuncias'
          )
          AND dup_ic.relname LIKE 'idx\_%' ESCAPE '\'
          AND array_length(dup_i.indkey::int2[], 1) = 1
          AND EXISTS (
              SELECT 1
              FROM pg_index canon_i
              JOIN pg_class canon_ic ON canon_ic.oid = canon_i.indexrelid
              JOIN pg_am canon_am ON canon_am.oid = canon_ic.relam AND canon_am.amname = 'gist'
              JOIN pg_attribute canon_a
                ON canon_a.attrelid = c.oid AND canon_a.attnum = canon_i.indkey[0]
              WHERE canon_i.indrelid = c.oid
                AND canon_i.indisvalid
                AND canon_i.indexrelid <> dup_i.indexrelid
                AND canon_ic.relname LIKE 'ix\_%' ESCAPE '\'
                AND array_length(canon_i.indkey::int2[], 1) = 1
                AND canon_a.attnum = dup_a.attnum
          )
    LOOP
        EXECUTE format('DROP INDEX IF EXISTS %I.%I', rec.schema_name, rec.dup_index);
    END LOOP;
END
$dedup_gist$;
"""

